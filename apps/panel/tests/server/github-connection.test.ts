import { afterEach, expect, it } from 'vitest';
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../../src/server/app.js';
import { Store } from '../../src/server/store.js';
import { hashPassword } from '../../src/server/auth.js';
import type { Service } from '../../src/shared/types.js';

const cleanups: (() => Promise<void>)[] = [];
afterEach(async () => { for (const cleanup of cleanups.splice(0).reverse()) await cleanup(); });

it('protects the shared connection and binds each deployment to the token at queue time', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'servus-github-'));
  const store = new Store(dir);
  const app = await createApp({dataDir:dir,store});
  cleanups.push(async () => { await app.close(); store.close(); rmSync(dir,{recursive:true,force:true}); });
  const setup = await app.inject({method:'POST',url:'/api/v1/setup',payload:{email:'admin@example.test',password:'12345678'}});
  const admin = {cookie:`panel_session=${setup.cookies.find(c => c.name === 'panel_session')!.value}`,'x-csrf-token':setup.json().csrfToken as string};
  const user = store.createUser('editor@example.test',await hashPassword('12345678'));
  const session = store.createSession(user.id);
  const editor = {cookie:`panel_session=${session.token}`,'x-csrf-token':session.csrfToken};
  const project1 = store.createProject('alpha'); const project2 = store.createProject('beta');
  store.addMember(project1.id,user.id,'editor');
  const endpoint='/api/v1/integrations/github';
  const secret1='example-token-alpha'; const secret2='example-token-bravo';
  expect((await app.inject({url:endpoint,headers:editor})).statusCode).toBe(403);
  expect((await app.inject({method:'PUT',url:endpoint,headers:editor,payload:{username:'git-user',token:secret1}})).statusCode).toBe(403);
  expect((await app.inject({method:'PUT',url:endpoint,headers:{cookie:admin.cookie},payload:{username:'git-user',token:secret1}})).statusCode).toBe(403);
  const saved = await app.inject({method:'PUT',url:endpoint,headers:admin,payload:{username:'git-user',token:secret1}});
  expect(saved.statusCode).toBe(200); expect(saved.body).not.toContain(secret1);
  expect((await app.inject({url:endpoint,headers:admin})).json()).toEqual({connected:true,username:'git-user'});
  for (const file of readdirSync(join(dir,'secrets'))) expect(readFileSync(join(dir,'secrets',file),'utf8')).not.toContain(secret1);
  expect(store.vault.redact(`token=${secret1}`)).not.toContain(secret1);
  const body=(name:string,repository:string)=>({name,hostname:`${name}.test`,source:{type:'git',repository,branch:'main',context:'.',dockerfile:'Dockerfile',sharedGithub:true}});
  const create=async(project:string,name:string,repository:string,headers:typeof admin=admin)=>app.inject({method:'POST',url:`/api/v1/projects/${project}/services`,headers:{...headers,'idempotency-key':`create-${name}`},payload:body(name,repository)});
  expect((await create(project1.id,'denied','https://github.com/org/private',editor)).statusCode).toBe(403);
  expect((await create(project1.id,'other','https://git.example.com/org/private')).statusCode).toBe(400);
  const one=await create(project1.id,'first','https://github.com/org/first');
  const two=await create(project2.id,'second','https://github.com/org/second');
  expect(one.statusCode).toBe(202);expect(two.statusCode).toBe(202);
  expect(one.body).not.toContain(secret1);expect(two.body).not.toContain(secret1);
  const first=one.json().service as Service;
  const job=(actionId:string)=>JSON.parse((store.db.prepare('SELECT snapshot FROM jobs WHERE action_id=?').get(actionId) as {snapshot:string}).snapshot) as Service;
  const tokenOf=(service:Service)=>{
    if(service.source?.type!=='git' || !service.source.credential?.secretRef)throw Error('Missing Git credential');
    return JSON.parse(store.vault.getServiceSecret(service.source.credential.secretRef,service.id,'git')).token as string;
  };
  expect(tokenOf(job(one.json().action.id))).toBe(secret1);
  expect((await app.inject({method:'PATCH',url:`/api/v1/services/${first.id}`,headers:editor,payload:{expectedRevision:first.revision,source:{type:'git',repository:'https://github.com/org/first',branch:'other',context:'.',dockerfile:'Dockerfile'}}})).statusCode).toBe(403);
  if (first.source?.type !== 'git') throw Error('Expected Git source');
  expect((await app.inject({method:'PATCH',url:`/api/v1/services/${first.id}`,headers:admin,payload:{expectedRevision:first.revision,source:{...first.source,sharedGithub:false}}})).statusCode).toBe(403);
  expect((await app.inject({method:'PUT',url:endpoint,headers:admin,payload:{username:'git-user',token:secret2}})).statusCode).toBe(200);
  expect(tokenOf(job(one.json().action.id))).toBe(secret1);
  store.db.prepare("UPDATE jobs SET status='succeeded' WHERE action_id=?").run(one.json().action.id);
  const deployment=await app.inject({method:'POST',url:`/api/v1/services/${first.id}/deploy`,headers:{...admin,'idempotency-key':'deploy-again'}});
  expect(deployment.statusCode).toBe(202); expect(tokenOf(job(deployment.json().id))).toBe(secret2);
  const same=await app.inject({method:'POST',url:`/api/v1/services/${first.id}/deploy`,headers:{...admin,'idempotency-key':'deploy-again'}});
  expect(same.json().id).toBe(deployment.json().id);
  const rotatedSnapshot=job(deployment.json().id);
  store.db.prepare("UPDATE jobs SET status='succeeded' WHERE action_id=?").run(deployment.json().id);
  const repeated=await app.inject({method:'POST',url:`/api/v1/services/${first.id}/deploy`,headers:{...admin,'idempotency-key':'same-credential'}});
  expect(repeated.statusCode).toBe(202);
  const repeatSnapshot=job(repeated.json().id);
  expect(repeatSnapshot.source?.type === 'git' && repeatSnapshot.source.credential?.secretRef).toBe(rotatedSnapshot.source?.type === 'git' && rotatedSnapshot.source.credential?.secretRef);
  store.db.prepare("UPDATE jobs SET status='succeeded' WHERE action_id=?").run(repeated.json().id);
  expect((await app.inject({method:'DELETE',url:endpoint,headers:admin})).statusCode).toBe(200);
  expect(tokenOf(job(deployment.json().id))).toBe(secret2);
  store.db.prepare("UPDATE jobs SET status='succeeded' WHERE action_id=?").run(deployment.json().id);
  expect((await app.inject({method:'POST',url:`/api/v1/services/${first.id}/deploy`,headers:{...admin,'idempotency-key':'after-disconnect'}})).statusCode).toBe(409);
  const removed=await app.inject({method:'PATCH',url:`/api/v1/services/${first.id}`,headers:admin,payload:{expectedRevision:first.revision,image:'nginx:alpine',source:{type:'image'}}});
  expect(removed.statusCode).toBe(200);
  const replay=await app.inject({method:'PATCH',url:`/api/v1/services/${first.id}`,headers:editor,payload:{expectedRevision:removed.json().revision,source:{...first.source,sharedGithub:false}}});
  expect(replay.statusCode).toBe(403);
});
